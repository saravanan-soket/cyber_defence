#!/usr/bin/env python3
"""Confirmed tasks -> a GLM-5.3 run config for `cvepatch benchmark`.

  python scripts/make_run_config.py --tasks runs/defensive-tasks \
      --out benchmarks/cvepatch-glm53.yaml [--lang go,python] [--limit 50] [--seeds 1,2]

Takes every bundle whose latest confirm result is REPRODUCIBLE (the reference
solution verified as T1 by the current verifier), so each env's verdict can reach every tier.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from cvepatch.core.verifier.verify import VERIFIER_VERSION  # noqa: E402

FIXTURE = Path(__file__).resolve().parent.parent / "benchmarks" / "cvepatch-fixture-glm53.yaml"


def runnable_setup(tasks: Path, rec: dict) -> bool:
    """Setup-mode tasks count only when confirmed on their agent-setup image."""
    hits = list(tasks.glob(f"*/{rec['task_id']}/hidden/task.json"))
    try:
        setup = json.loads(hits[0].read_text())["metadata"].get("setup_mode") if hits else None
    except (OSError, ValueError, KeyError):
        return False
    return setup != "agent" or bool(rec.get("on_setup_image"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tasks", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--lang", default="", help="comma-separated filter")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--seeds", default="1")
    ap.add_argument("--max-parallel", type=int, default=2)
    ap.add_argument("--benchmark-id", default="cvepatch-glm53")
    ap.add_argument("--include-buildable", action="store_true",
                    help="also include no-upstream-oracle tasks confirmed BUILDABLE")
    a = ap.parse_args()
    langs = {x.strip() for x in a.lang.split(",") if x.strip()}
    confirmed = [json.loads(ln) for ln in (a.tasks / "confirm.jsonl").read_text().splitlines()]
    # REPRODUCIBLE = reference solution verified T1 (has an upstream oracle).
    # BUILDABLE = no upstream test, but the image builds and the fix compiles;
    # the agent still gets a valid task (verifier tier <= T2 at run time).
    want = {"REPRODUCIBLE", "BUILDABLE"} if a.include_buildable else {"REPRODUCIBLE"}
    ok = sorted(r["task_id"] for r in confirmed if r.get("status") in want
                and r.get("verifier") == VERIFIER_VERSION and runnable_setup(a.tasks, r))
    envs = []
    for task_id in ok:
        lang = task_id.split("-", 1)[0]
        if langs and lang not in langs:
            continue
        envs.append({"id": f"defensive-{task_id}", "image": f"local/defensive-{task_id}:latest",
                     "task_type": "binary_patch",
                     "interface": "rl.mcp.vulnerability_defense.v1"})
    if a.limit:
        envs = envs[: a.limit]
    base = yaml.safe_load(FIXTURE.read_text())
    cfg = {**base, "benchmark_id": a.benchmark_id, "envs": envs,
           "seeds": [int(s) for s in a.seeds.split(",")], "max_parallel": a.max_parallel,
           "episode_timeout_s": 5400}
    cfg["budgets"] = {**base["budgets"], "turn_budget": 150}
    a.out.write_text("# generated by scripts/make_run_config.py\n" + yaml.safe_dump(cfg, sort_keys=False))
    print(f"{len(envs)} envs -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
